import { useMemo, useState } from "react";
import { useNavigate } from "react-router-dom";
import { Alert } from "../../components/common/Alert";
import { Badge } from "../../components/common/Badge";
import { Button } from "../../components/common/Button";
import { Card, SectionHeader } from "../../components/common/Card";
import { Field, inputClass } from "../../components/common/Form";
import { Modal } from "../../components/common/Modal";
import { PageHeader } from "../../components/common/PageHeader";
import { Pagination } from "../../components/common/Pagination";
import { ErrorState, LoadingState } from "../../components/common/State";
import { DataTable } from "../../components/common/Table";
import { listMyAttendance } from "../../api/employeeSelfService";
import { useAsync } from "../../hooks/useAsync";
import type { AttendanceRecord } from "../../types/api";
import { formatDate, formatDateTime } from "../../utils/dateTime";
import { canRequestAttendanceReview, requestReviewPath } from "../../utils/employeeRequestShortcuts";
import { formatEnumLabel, formatHours } from "../../utils/formatters";

const statusOptions = ["", "PRESENT", "LATE", "EARLY_DEPARTURE", "MISSING_CHECKOUT", "ABSENT", "UNSCHEDULED"];

function scheduledValue(record: AttendanceRecord, value?: string | null): string {
  // Returns the scheduled datetime display value.
  return record.is_unscheduled ? "Not applicable" : formatDateTime(value);
}

function scheduleName(record: AttendanceRecord): string {
  // Returns the schedule display name.
  return record.is_unscheduled ? "Unscheduled" : (record.schedule_template_name ?? "Not assigned");
}

function issueMinutes(record: AttendanceRecord, value: number, applies: boolean): string {
  // Returns the issue-minute display value.
  return record.is_unscheduled || !applies ? "Not applicable" : `${value} min`;
}

export function MyAttendancePage() {
  const navigate = useNavigate();
  const [filters, setFilters] = useState({
    date_from: "",
    date_to: "",
    status: "",
    page: 1,
    page_size: 10,
  });
  const [selected, setSelected] = useState<AttendanceRecord | null>(null);

  const query = useMemo(
    // Builds the attendance query from non-empty filters.
    () =>
      Object.fromEntries(
        Object.entries(filters).filter(([, value]) => value !== "" && value !== null && value !== undefined),
      ),
    [filters],
  );

  const attendance = useAsync(() => listMyAttendance(query), [JSON.stringify(query)]);

  function updateFilter(key: keyof typeof filters, value: string | number) {
    setFilters((current) => ({ ...current, [key]: value, page: key === "page" ? Number(value) : 1 }));
  }

  return (
    <div className="page-stack">
      <PageHeader title="My Attendance" description="Read-only attendance history generated by the camera-based face-recognition workflow." />
      <Card>
        <SectionHeader title="Filter attendance" description="Narrow your history by date range or attendance status." />
        <div className="grid gap-4 md:grid-cols-4">
          <Field label="Date from">
            <input className={inputClass} type="date" value={filters.date_from} onChange={(event) => updateFilter("date_from", event.target.value)} />
          </Field>
          <Field label="Date to">
            <input className={inputClass} type="date" value={filters.date_to} onChange={(event) => updateFilter("date_to", event.target.value)} />
          </Field>
          <Field label="Status">
            <select className={inputClass} value={filters.status} onChange={(event) => updateFilter("status", event.target.value)}>
              {statusOptions.map((status) => (
                <option key={status || "all"} value={status}>
                  {status ? formatEnumLabel(status) : "All statuses"}
                </option>
              ))}
            </select>
          </Field>
          <div className="flex items-end">
            <Button
              variant="secondary"
              onClick={() => setFilters({ date_from: "", date_to: "", status: "", page: 1, page_size: 10 })}
              className="w-full"
            >
              Clear filters
            </Button>
          </div>
        </div>
      </Card>

      <Card>
        <SectionHeader title="Attendance records" description="Select View for a complete record breakdown." />
        {attendance.loading ? (
          <LoadingState label="Loading your attendance records..." />
        ) : attendance.error ? (
          <ErrorState message={attendance.error} />
        ) : (
          <>
            <DataTable<AttendanceRecord>
              rowKey={(row) => row.id}
              rows={attendance.data?.items ?? []}
              emptyTitle="No attendance records found"
              empty="Try changing the date range or status filter. Records appear after the camera-based system creates them."
              columns={[
                { header: "Date", render: (row) => formatDate(row.schedule_date) },
                { header: "Schedule", render: (row) => scheduleName(row) },
                { header: "Check in", render: (row) => formatDateTime(row.check_in_at) },
                { header: "Check out", render: (row) => formatDateTime(row.check_out_at) },
                { header: "Status", render: (row) => <Badge value={row.effective_status || row.status} /> },
                { header: "Justification", render: (row) => (row.latest_justification_status ? <Badge value={row.latest_justification_status} /> : "None") },
                { header: "Overtime", render: (row) => (row.latest_overtime_status ? <Badge value={row.latest_overtime_status} /> : "None") },
                {
                  header: "Request",
                  render: (row) =>
                    canRequestAttendanceReview(row) ? (
                      // Opens a request-review form for this attendance record.
                      <Button size="sm" variant="secondary" onClick={() => navigate(requestReviewPath(row))}>Request Review</Button>
                    ) : (
                      <span className="text-slate-400">Not eligible</span>
                    ),
                },
                {
                  header: "Details",
                  render: (row) => (
                    <Button size="sm" variant="secondary" onClick={() => setSelected(row)}>
                      View
                    </Button>
                  ),
                },
              ]}
            />
            <Pagination
              page={attendance.data?.page ?? filters.page}
              pageSize={attendance.data?.page_size ?? filters.page_size}
              total={attendance.data?.total ?? 0}
              onPageChange={(page) => updateFilter("page", page)}
            />
          </>
        )}
      </Card>

      <Modal
        open={Boolean(selected)}
        title={selected ? `Attendance record - ${formatDate(selected.schedule_date)}` : "Attendance record"}
        description="Camera-generated attendance details are read-only. Use Request Review when an eligible fact needs administrative review."
        onClose={() => setSelected(null)}
        size="md"
        footer={
          <div className="action-row">
            <Button variant="secondary" onClick={() => setSelected(null)}>Close</Button>
            {selected && canRequestAttendanceReview(selected) ? (
              <Button onClick={() => {
                const path = requestReviewPath(selected);
                setSelected(null);
                navigate(path);
              }}>Request Review</Button>
            ) : null}
          </div>
        }
      >
        {selected ? (
          <div className="space-y-5">
            <div className="grid gap-3 text-sm sm:grid-cols-2">
              {([
                ["Status", <Badge value={selected.effective_status || selected.status} />],
                ["Original status", <Badge value={selected.original_status || selected.status} />],
                ["Schedule", scheduleName(selected)],
                ["Scheduled start", scheduledValue(selected, selected.scheduled_start_datetime)],
                ["Scheduled end", scheduledValue(selected, selected.scheduled_end_datetime)],
                ["Check-in", formatDateTime(selected.check_in_at)],
                ["Check-out", formatDateTime(selected.check_out_at)],
                ["Working hours", formatHours(selected.working_hours)],
                ["Late minutes", issueMinutes(selected, selected.late_minutes, selected.is_late)],
                ["Early departure minutes", issueMinutes(selected, selected.early_departure_minutes, selected.is_early_departure)],
                ["Justification status", selected.latest_justification_status ?? "None"],
                ["Overtime status", selected.latest_overtime_status ?? "None"],
              ] as [string, React.ReactNode][]).map(([label, value]) => (
                <div key={label} className="rounded-md bg-slate-50 p-4">
                  <p className="font-semibold text-slate-500">{label}</p>
                  <p className="mt-1 font-bold text-ink">{value}</p>
                </div>
              ))}
            </div>
            <Alert tone="info">If this record needs review, submit an eligible justification request for administrative review.</Alert>
          </div>
        ) : null}
      </Modal>
    </div>
  );
}
