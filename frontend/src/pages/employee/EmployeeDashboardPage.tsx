import { AlertCircle, CalendarClock, ClipboardList, Timer, UserRoundCheck } from "lucide-react";
import { useNavigate } from "react-router-dom";
import { Alert } from "../../components/common/Alert";
import { Badge } from "../../components/common/Badge";
import { Button } from "../../components/common/Button";
import { Card, SectionHeader } from "../../components/common/Card";
import { PageHeader } from "../../components/common/PageHeader";
import { DataTable } from "../../components/common/Table";
import { EmptyState, ErrorState, LoadingState } from "../../components/common/State";
import { getMyAttendanceSummary, getMyEffectiveSchedule, listMyAttendance, listMyJustificationRequests, listMyOvertimeRequests } from "../../api/employeeSelfService";
import { useAsync } from "../../hooks/useAsync";
import type { AttendanceRecord } from "../../types/api";
import { formatDate, formatDateTime, todayIsoDate } from "../../utils/dateTime";
import { canRequestAttendanceReview, requestReviewPath } from "../../utils/employeeRequestShortcuts";

function monthRange(today: string) {
  const [year, month] = today.split("-").map(Number);
  const start = `${year}-${String(month).padStart(2, "0")}-01`;
  const endDate = new Date(year, month, 0);
  const end = `${year}-${String(month).padStart(2, "0")}-${String(endDate.getDate()).padStart(2, "0")}`;
  return { start, end };
}

function MetricCard({ title, value, hint, icon: Icon }: { title: string; value: string | number; hint?: string; icon: any }) {
  return (
    <div className="min-h-28 border-b border-slate-200 p-4 sm:border-r">
      <div className="flex items-center gap-2 text-slate-500">
        <Icon className="h-4 w-4 text-signal-700" strokeWidth={1.8} />
        <p className="text-[0.6875rem] font-semibold uppercase tracking-[0.08em]">{title}</p>
      </div>
      <p className="mt-3 font-display text-xl font-semibold tabular-nums text-ink">{value}</p>
      {hint ? <p className="mt-1.5 text-xs leading-5 text-slate-500">{hint}</p> : null}
    </div>
  );
}

export function EmployeeDashboardPage() {
  const navigate = useNavigate();
  const today = todayIsoDate();
  const range = monthRange(today);
  // Loads the employee dashboard data from self-service endpoints.
  const attendance = useAsync(() => listMyAttendance({ on_date: today, page: 1, page_size: 5 }), [today]);
  const schedule = useAsync(() => getMyEffectiveSchedule(today), [today]);
  const summary = useAsync(() => getMyAttendanceSummary({ date_from: range.start, date_to: range.end }), [range.start, range.end]);
  const justifications = useAsync(() => listMyJustificationRequests({ status: "PENDING", page: 1, page_size: 5 }), []);
  const overtime = useAsync(() => listMyOvertimeRequests({ status: "PENDING", page: 1, page_size: 5 }), []);

  // Selects today's attendance record for status and review actions.
  const todayRecord = attendance.data?.items[0];
  const pendingRequests = (justifications.data?.total ?? 0) + (overtime.data?.total ?? 0);

  return (
    <div className="page-stack">
      <PageHeader
        eyebrow="Today"
        title={formatDate(today)}
        description="Attendance shown here is generated by the camera-based recognition system. This portal has no manual check-in or check-out controls."
        action={<div className="flex flex-wrap items-center gap-3">
            {todayRecord ? <Badge value={todayRecord.effective_status || todayRecord.status} /> : <Badge value="NO_RECORD" label="No record yet" />}
            {canRequestAttendanceReview(todayRecord) ? (
              <Button variant="secondary" onClick={() => navigate(requestReviewPath(todayRecord!))}>Request Review</Button>
            ) : null}
          </div>}
      />

      <section className="overflow-hidden rounded-lg border border-slate-300 bg-white shadow-card" aria-label="Employee attendance indicators">
        <div className="border-b border-slate-300 bg-slate-50 px-4 py-3">
          <h2 className="text-sm font-semibold text-ink">Today at a glance</h2>
          <p className="mt-0.5 text-xs text-slate-500">Camera-generated attendance status and your current request workload.</p>
        </div>
        <div className="grid md:grid-cols-2 xl:grid-cols-4 [&>*:last-child]:border-r-0">
          <MetricCard title="Check-in time" value={formatDateTime(todayRecord?.check_in_at)} icon={UserRoundCheck} />
          <MetricCard title="Check-out time" value={formatDateTime(todayRecord?.check_out_at)} icon={Timer} />
          <MetricCard title="Monthly late records" value={summary.data?.summary.late_count ?? 0} icon={AlertCircle} hint={`${range.start} to ${range.end}`} />
          <MetricCard title="Pending requests" value={pendingRequests} icon={ClipboardList} hint="Awaiting administrative review" />
        </div>
      </section>

      <section className="grid gap-4 xl:grid-cols-[0.82fr_1.18fr]">
        <Card>
          <SectionHeader title="Assigned Schedule" />
          {schedule.loading ? (
            <LoadingState label="Loading your schedule..." />
          ) : schedule.error ? (
            <ErrorState message={schedule.error} />
          ) : schedule.data?.has_schedule ? (
            <dl className="divide-y divide-slate-200 border-y border-slate-200 text-sm">
              <div className="grid grid-cols-[8rem_1fr] gap-3 py-3">
                <dt className="font-medium text-slate-500">Schedule</dt>
                <dd className="text-right font-semibold text-ink">{schedule.data.schedule_template_name}</dd>
              </div>
              <div className="grid grid-cols-[8rem_1fr] gap-3 py-3">
                <dt className="font-medium text-slate-500">Shift window</dt>
                <dd className="text-right font-semibold text-ink">
                  {formatDateTime(schedule.data.scheduled_start_datetime)} to {formatDateTime(schedule.data.scheduled_end_datetime)}
                </dd>
              </div>
              <div className="grid grid-cols-[8rem_1fr] items-center gap-3 py-3">
                <dt className="font-medium text-slate-500">Day status</dt>
                <dd className="text-right"><Badge value={schedule.data.working_day} label={schedule.data.working_day ? "Working day" : "Not working today"} /></dd>
              </div>
            </dl>
          ) : (
            <EmptyState title="No active schedule for today" description={schedule.data?.message ?? "No effective schedule was returned for this date."} />
          )}
        </Card>

        <Card>
          <SectionHeader title="Recent Attendance" action={<Button variant="secondary" onClick={() => navigate("/employee/attendance")}>View all</Button>} />
          <div>
            {attendance.loading ? (
              <LoadingState label="Loading today's attendance..." />
            ) : attendance.error ? (
              <ErrorState message={attendance.error} />
            ) : (
              <DataTable<AttendanceRecord>
                rowKey={(row) => row.id}
                rows={attendance.data?.items ?? []}
                emptyTitle="No attendance record for today"
                empty="Your attendance will appear after the camera-based system records it."
                columns={[
                  { header: "Date", render: (row) => formatDate(row.schedule_date) },
                  { header: "Check in", render: (row) => formatDateTime(row.check_in_at) },
                  { header: "Check out", render: (row) => formatDateTime(row.check_out_at) },
                  { header: "Status", render: (row) => <Badge value={row.effective_status || row.status} /> },
                  {
                    header: "Action",
                    render: (row) =>
                      canRequestAttendanceReview(row) ? (
                        <Button size="sm" variant="secondary" onClick={() => navigate(requestReviewPath(row))}>Request Review</Button>
                      ) : (
                        <span className="text-slate-400">No action</span>
                      ),
                  },
                ]}
              />
            )}
          </div>
        </Card>
      </section>

      {summary.data?.requires_daily_processing_for_complete_absence_metrics ? (
        <Alert tone="warning" title="Processing notice">
          Absence and missing-checkout statistics depend on completed daily processing by the administration workflow.
        </Alert>
      ) : null}

      <Card>
        <SectionHeader title="Monthly Summary" action={<CalendarClock className="h-5 w-5 text-ocean-700" aria-hidden="true" />} />
        {summary.loading ? (
          <LoadingState label="Loading monthly summary..." />
        ) : summary.error ? (
          <ErrorState message={summary.error} />
        ) : (
          <div className="grid overflow-hidden rounded-md border border-slate-300 md:grid-cols-2 xl:grid-cols-5 [&>*:last-child]:border-r-0">
            <MetricCard title="Records" value={summary.data?.summary.total_records ?? 0} icon={ClipboardList} />
            <MetricCard title="Absent" value={summary.data?.summary.absent_count ?? 0} icon={AlertCircle} />
            <MetricCard title="Missing checkout" value={summary.data?.summary.missing_checkout_count ?? 0} icon={Timer} />
            <MetricCard title="Overtime hours" value={summary.data?.summary.approved_overtime_hours ?? 0} icon={Timer} />
            <MetricCard
              title="Attendance rate"
              value={summary.data?.summary.attendance_rate_percentage == null ? "N/A" : `${summary.data.summary.attendance_rate_percentage}%`}
              icon={UserRoundCheck}
            />
          </div>
        )}
      </Card>
    </div>
  );
}
